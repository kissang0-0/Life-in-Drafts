export function getDailyNimbusMessage(mood?: string): string {
  const seed = mood ? mood.charCodeAt(0) + mood.length : 0;
  if (mood && NIMBUS_MOOD[mood] && NIMBUS_MOOD[mood].length > 0) {
    return pickForDay(NIMBUS_MOOD[mood], seed);
  }
  return pickForDay(NIMBUS_GENERAL, 0);
}
