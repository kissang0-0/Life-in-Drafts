const DAY_MS = 86400000;

function dayIndex(): number {
  const now = new Date();
  return Math.floor(now.getTime() / DAY_MS);
}

function pickForDay<T>(arr: T[], seed: number): T {
  return arr[(dayIndex() + seed) % arr.length];
}

